"""Export the canonical API schema and dependency-free mobile TypeScript DTOs."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from benma_api.app import create_app
from benma_api.config import Settings

ROOT = Path(__file__).resolve().parents[3]
OPENAPI_PATH = ROOT / "apps/mobile/src/api/openapi.json"
TYPES_PATH = ROOT / "apps/mobile/src/api/openapi.generated.ts"


def ts_literal(value: object) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    return json.dumps(value, ensure_ascii=False)


def ts_type(schema: dict[str, Any]) -> str:
    reference = schema.get("$ref")
    if isinstance(reference, str):
        name = reference.rsplit("/", 1)[-1]
        return f'components["schemas"][{json.dumps(name)}]'

    for union_key in ("anyOf", "oneOf"):
        union = schema.get(union_key)
        if isinstance(union, list):
            return " | ".join(ts_type(item) for item in union if isinstance(item, dict))

    enum = schema.get("enum")
    if isinstance(enum, list):
        return " | ".join(ts_literal(item) for item in enum)

    schema_type = schema.get("type")
    if schema_type == "array":
        items = schema.get("items")
        item_type = ts_type(items) if isinstance(items, dict) else "unknown"
        return f"Array<{item_type}>"
    if schema_type == "object" or "properties" in schema or "additionalProperties" in schema:
        properties = schema.get("properties", {})
        required = set(schema.get("required", []))
        members: list[str] = []
        if isinstance(properties, dict):
            for name, value in properties.items():
                if isinstance(value, dict):
                    optional = "" if name in required else "?"
                    members.append(
                        f"    {json.dumps(name)}{optional}: {ts_type(value)};"
                    )
        additional = schema.get("additionalProperties")
        if additional is True:
            members.append("    [key: string]: unknown;")
        elif isinstance(additional, dict):
            members.append(f"    [key: string]: {ts_type(additional)};")
        if not members:
            return "{}"
        return "{\n" + "\n".join(members) + "\n  }"
    if schema_type == "string":
        return "string"
    if schema_type in {"integer", "number"}:
        return "number"
    if schema_type == "boolean":
        return "boolean"
    if schema_type == "null":
        return "null"
    return "unknown"


def render_types(schema: dict[str, Any]) -> str:
    schemas = schema.get("components", {}).get("schemas", {})
    if not isinstance(schemas, dict):
        raise RuntimeError("OpenAPI components.schemas is missing")
    lines = [
        "/* eslint-disable */",
        "// Generated by services/api/scripts/export_openapi.py. Do not edit.",
        "export interface components {",
        '  "schemas": {',
    ]
    for name, value in sorted(schemas.items()):
        if isinstance(value, dict):
            rendered = ts_type(value).replace("\n", "\n    ")
            lines.append(f"    {json.dumps(name)}: {rendered};")
    lines.extend(["  };", "}", ""])
    return "\n".join(lines)


def write_if_changed(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != content:
        path.write_text(content)


def main() -> None:
    settings = Settings(
        environment="test",
        database_url="sqlite://",
        audio_storage_dir=Path("/tmp/benma-openapi-audio"),
        dev_auth_enabled=True,
        perception_provider="replay",
        assessment_provider="replay",
    )
    schema = create_app(settings).openapi()
    openapi_json = json.dumps(schema, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    write_if_changed(OPENAPI_PATH, openapi_json)
    write_if_changed(TYPES_PATH, render_types(schema))
    print(f"wrote {OPENAPI_PATH.relative_to(ROOT)}")
    print(f"wrote {TYPES_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
